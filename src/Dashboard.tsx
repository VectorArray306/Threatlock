import { useState } from "react";
import { Info, ShieldCheck } from "lucide-react";
import type { Incident, Severity } from "./policy";
import { personas, severityColors, syntheticHistory } from "./history";
interface Props {
  incidents: Incident[];
  onReview: (id: string, disposition: Incident["disposition"]) => void;
}
const severities: Severity[] = ["none", "caution", "high", "critical"];
export default function Dashboard({ incidents, onReview }: Props) {
  const [source, setSource] = useState<"live" | "synthetic">("live");
  const [persona, setPersona] = useState("all");
  const dataset = source === "live" ? incidents : syntheticHistory;
  const visible =
    source === "synthetic" && persona !== "all"
      ? dataset.filter((incident) => incident.personaId === persona)
      : dataset;
  return (
    <>
      <div className="stats">
        {[
          ["Live session events", incidents.length],
          [
            "Live awaiting review",
            incidents.filter((i) => i.disposition === "open").length,
          ],
          [
            "Live policy blocks",
            incidents.filter((i) => i.risk === 100).length,
          ],
          ["Dashboard content retained", "0"],
        ].map(([title, value]) => (
          <div className="card" key={title}>
            <span>{title}</span>
            <strong>{value}</strong>
            <small>This browser session only</small>
          </div>
        ))}
      </div>
      <div
        className="dataset-controls"
        role="group"
        aria-label="Dashboard data source"
      >
        <button
          aria-pressed={source === "live"}
          onClick={() => setSource("live")}
        >
          Live session ({incidents.length})
        </button>
        <button
          aria-pressed={source === "synthetic"}
          onClick={() => setSource("synthetic")}
        >
          Synthetic history ({syntheticHistory.length})
        </button>
      </div>
      {source === "synthetic" ? (
        <>
          <div className="demo-banner">
            <Info size={18} />
            <span>
              <strong>Seeded synthetic history.</strong> These 12 fictional
              events represent a sample day on 18 October 2026. They are
              read-only examples and never count as live-session activity.
            </span>
          </div>
          <div className="persona-grid">
            {personas.map((person) => (
              <section className="card" key={person.id}>
                <span className="eyebrow">FICTIONAL PERSONA</span>
                <h2>{person.name}</h2>
                <p>{person.role}</p>
                <strong>
                  {
                    syntheticHistory.filter((i) => i.personaId === person.id)
                      .length
                  }{" "}
                  sample events
                </strong>
              </section>
            ))}
          </div>
          <label htmlFor="persona-filter">Inspect a fictional persona</label>
          <select
            id="persona-filter"
            value={persona}
            onChange={(e) => setPersona(e.target.value)}
          >
            <option value="all">All three personas</option>
            {personas.map((person) => (
              <option key={person.id} value={person.id}>
                {person.name}
              </option>
            ))}
          </select>
        </>
      ) : (
        <div className="demo-banner">
          <Info size={18} />
          <span>
            <strong>Live session.</strong> Only events generated by your local
            walkthrough appear below. Incoming signals and outgoing checks are
            counted separately; repeating the same check adds no duplicate
            event.
          </span>
        </div>
      )}
      <section className="card activity-card">
        <h2>
          Activity by hour ·{" "}
          {source === "live" ? "live session" : "synthetic sample day"}
        </h2>
        <p>
          Each cell shows an event count; its color represents the highest
          severity in that hour. Times use your browser’s local time.
        </p>
        <div className="heatmap">
          {Array.from({ length: 24 }, (_, hour) => {
            const events = visible.filter(
              (incident) => new Date(incident.time).getHours() === hour,
            );
            const severity = severities
              .slice()
              .reverse()
              .find((severity) =>
                events.some((event) => event.severity === severity),
              );
            return (
              <div
                key={hour}
                title={`${hour}:00 — ${events.length} events${severity ? `, highest severity ${severity}` : ""}`}
                style={{
                  background: severity ? severityColors[severity] : "#edf2ef",
                  color: severity ? "#fff" : "#67815e",
                }}
              >
                <span>{String(hour).padStart(2, "0")}:00</span>
                <strong>{events.length}</strong>
              </div>
            );
          })}
        </div>
        <h3 className="distribution-title">
          Severity distribution · {visible.length} events
        </h3>
        <div className="severity-distribution">
          {severities.map((severity) => {
            const count = visible.filter(
              (event) => event.severity === severity,
            ).length;
            return (
              <div key={severity}>
                <span>
                  <i style={{ background: severityColors[severity] }} />
                  {severity === "none" ? "Informational" : severity}
                  <strong>{count}</strong>
                </span>
                <div className="distribution-track">
                  <i
                    style={{
                      width: `${visible.length ? (count / visible.length) * 100 : 0}%`,
                      background: severityColors[severity],
                    }}
                  />
                </div>
              </div>
            );
          })}
        </div>
      </section>
      <section className="card events">
        <h2>
          {source === "live"
            ? "Live security events"
            : "Synthetic security events"}
        </h2>
        <p>
          Metadata only: fictional persona, direction, reason, severity, source,
          time, and disposition. Drafts and attachment contents are never
          retained in event records.
        </p>
        {!visible.length ? (
          <div className="empty">
            <ShieldCheck />
            <h3>No events yet</h3>
            <p>
              Advance a suspicious scenario or check a draft in the simulator.
            </p>
          </div>
        ) : (
          <div className="table-scroll">
            <table>
              <thead>
                <tr>
                  <th>Time</th>
                  <th>Persona / direction</th>
                  <th>Reason</th>
                  <th>Risk</th>
                  <th>Source</th>
                  <th>Status</th>
                  <th>Review</th>
                </tr>
              </thead>
              <tbody>
                {visible.map((incident) => (
                  <tr key={incident.id}>
                    <td>{new Date(incident.time).toLocaleTimeString()}</td>
                    <td>
                      {personas.find(
                        (person) => person.id === incident.personaId,
                      )?.name || "Demo presenter"}
                      <small className="event-direction">
                        {incident.direction}
                      </small>
                    </td>
                    <td>{incident.reason.replaceAll("_", " ")}</td>
                    <td>
                      {incident.risk ?? "Unscored"} · {incident.severity}
                    </td>
                    <td>{incident.source}</td>
                    <td>{incident.disposition}</td>
                    <td>
                      {source === "synthetic" ? (
                        <span className="seeded-label">Read-only sample</span>
                      ) : (
                        <>
                          <button
                            onClick={() =>
                              onReview(incident.id, "acknowledged")
                            }
                          >
                            Acknowledge
                          </button>
                          <button
                            onClick={() => onReview(incident.id, "escalated")}
                          >
                            Escalate
                          </button>
                        </>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </section>
    </>
  );
}
